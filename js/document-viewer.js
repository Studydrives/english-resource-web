
'use strict';

/**
 * HUFLIT English Hub
 * Document viewer modal
 */

function openDocModal(resourceId) {
    const modal = document.getElementById('docModal');

    if (!modal || typeof resourcesData === 'undefined') {
        console.error('[DocumentViewer] Modal or resource data not found.');
        return;
    }

    const resource = resourcesData.find(
        (item) => Number(item.id) === Number(resourceId)
    );

    if (!resource) {
        console.error('[DocumentViewer] Resource not found:', resourceId);
        return;
    }

    // Match the actual IDs in index.html.
    const title = modal.querySelector('#modalTitle');
    const content = modal.querySelector('#modalBody');
    const category = modal.querySelector('#modalCategory');
    const pageBadge = modal.querySelector('#modalPageBadge');
    const subtitle = modal.querySelector('#modalSubTitle');

    if (!title || !content) {
        console.error('[DocumentViewer] Modal content elements not found.');
        return;
    }

    title.textContent = resource.title || 'Untitled document';

    if (category) {
        category.textContent = resource.category || 'General';
    }

    if (pageBadge) {
        pageBadge.textContent = `Page ${resource.id} / ${resourcesData.length}`;
    }

    if (subtitle) {
        subtitle.textContent = resource.desc || '';
    }

    /*
     * resourcesData is project-authored static content.
     * Its content field intentionally contains HTML generated by
     * createFullPageSheet() in js/resources.js.
     * Do not insert untrusted user-provided HTML here.
     */
    content.innerHTML = resource.content || '';

    modal.classList.remove('hidden');
    modal.classList.add('flex');
    modal.setAttribute('aria-hidden', 'false');

    document.body.style.overflow = 'hidden';

    const closeButton = modal.querySelector(
        '[onclick="closeDocModal()"]'
    );

    closeButton?.focus();
}

function closeDocModal() {
    const modal = document.getElementById('docModal');

    if (!modal) {
        return;
    }

    modal.classList.remove('flex');
    modal.classList.add('hidden');
    modal.setAttribute('aria-hidden', 'true');

    document.body.style.overflow = '';
}

document.addEventListener('DOMContentLoaded', () => {
    const modal = document.getElementById('docModal');

    if (!modal) {
        console.error('[DocumentViewer] Modal element not found.');
        return;
    }

    modal.addEventListener('click', (event) => {
        if (event.target === modal) {
            closeDocModal();
        }
    });

    document.addEventListener('keydown', (event) => {
        if (
            event.key === 'Escape' &&
            !modal.classList.contains('hidden')
        ) {
            closeDocModal();
        }
    });
});
